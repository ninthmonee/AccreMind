import * as fs from 'node:fs'; import * as os from 'node:os'; import * as path from 'node:path';
import { createAccreMindRuntime } from '@accremind/dsh-plugin';
const base = fs.mkdtempSync(path.join(os.tmpdir(), 'pl-')); fs.mkdirSync(path.join(base,'repo'));
const rt = createAccreMindRuntime({ projectRoot: path.join(base,'repo'), globalDir: path.join(base,'g') });
const { token } = await rt.rpcHandlers['accremind.demo.open']!({}) as { token: string };
const call = (m: string, p = {}) => rt.rpcHandlers['accremind.demo.call']!({ token, method: m, params: p }) as any;
const q = await call('accremind.gov.reviewQueue');
const e = q.staleEntries[0];
const d = await call('accremind.gov.reviewDetails', { id: e.id, revision: e.revision });
console.log(JSON.stringify(d.evidence.map((x: any) => ({ id: x.evidenceId, changed: x.changed, ver: x.verification, then: x.then?.excerpt.slice(0, 80), now: x.now.excerpt.slice(0, 80) })), null, 1));
const g = await call('accremind.kb.get', { id: 'K-0901' });
console.log(g.snapshots.length, JSON.stringify(g.ledger.standing));
console.log(JSON.stringify(await call('accremind.ledger.status')).slice(0, 300));
await rt.rpcHandlers['accremind.demo.close']!({ token });
